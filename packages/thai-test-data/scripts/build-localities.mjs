//
//   git clone https://github.com/kongvut/thai-province-data
//   node scripts/build-localities.mjs thai-province-data/api/latest/province_with_district_and_sub_district.json
//
// The output is a compact nested array so the browser demo stays small.
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE_COMMIT = "3dddbb0";
const input = process.argv[2];
if (!input) {
  console.error("Usage: node scripts/build-localities.mjs <province_with_district_and_sub_district.json>");
  process.exit(1);
}

const provinces = JSON.parse(readFileSync(input, "utf8"))
  .filter((p) => !p.deleted_at)
  .sort((a, b) => a.name.th.localeCompare(b.name.th, "th"))
  .map((p) => [
    p.name.th,
    p.name.en,
    p.districts
      .filter((d) => !d.deleted_at)
      .map((d) => [
        d.name.th,
        d.name.en,
        d.sub_districts.filter((s) => !s.deleted_at).map((s) => [s.name.th, s.name.en, String(s.zip_code)]),
      ]),
  ]);

const subdistricts = provinces.reduce((n, p) => n + p[2].reduce((m, d) => m + d[2].length, 0), 0);
const out = `// Generated by scripts/build-localities.mjs. Do not edit by hand.
// Source: https://github.com/kongvut/thai-province-data (commit ${SOURCE_COMMIT})
// Copyright (c) 2025 Kongvut Sangkla, MIT License. See THIRD_PARTY_NOTICES.md.
// ${provinces.length} provinces, ${subdistricts} subdistricts.
// Shape: [provinceTh, provinceEn, [[districtTh, districtEn, [[subdistrictTh, subdistrictEn, postalCode]]]]]

export type ProvinceRow = readonly [string, string, readonly (readonly [string, string, readonly (readonly [string, string, string])[]])[]];

export const PROVINCE_ROWS: readonly ProvinceRow[] = ${JSON.stringify(provinces)};
`;
writeFileSync(new URL("../src/data/localities.ts", import.meta.url), out);
console.log(`Wrote ${provinces.length} provinces, ${subdistricts} subdistricts`);
